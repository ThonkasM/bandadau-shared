// Regenerates src/generated/ from ../bandadau-docs/contracts. Output is committed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { generate } from '@graphql-codegen/cli';
import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const contracts = path.resolve(process.env.CONTRACTS_DIR ?? path.join(root, '../../../bandadau-docs/contracts'));
const out = path.join(root, 'src/generated');
const BANNER = '/* eslint-disable */\n/* Generated by `pnpm contracts:gen` from bandadau-docs/contracts. Do not edit. */\n\n';

const write = (file, content) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
};

async function toTypes(input) {
  return astToString(await openapiTS(input, { alphabetize: true }));
}

async function genOpenApi() {
  const dir = path.join(contracts, 'openapi');
  const services = [];
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('-service.yaml')).sort()) {
    const service = file.replace(/-service\.yaml$/, '');
    write(path.join(out, 'openapi', `${service}.ts`), BANNER + (await toTypes(pathToFileURL(path.join(dir, file)))));
    services.push(service);
  }
  return services;
}

const pascal = (s) => s.replace(/(^|[-_.])(\w)/g, (_, __, c) => c.toUpperCase());

async function genEvents() {
  const doc = parse(fs.readFileSync(path.join(contracts, 'asyncapi/bandada-events.yaml'), 'utf8'));
  const schemas = { ...doc.components.schemas };
  const entries = [];
  for (const [name, message] of Object.entries(doc.components.messages)) {
    const parts = message.payload?.allOf ?? [];
    const body = parts.find((p) => p.properties?.type?.const);
    if (!body) throw new Error(`Message ${name}: cannot find payload.allOf[].properties.type.const`);
    const type = body.properties.type.const;
    const source = body.properties.source?.const ?? null;
    let dataRef = body.properties.data?.$ref;
    if (!dataRef) {
      const inline = body.properties.data;
      if (!inline) throw new Error(`Message ${name} has no data`);
      schemas[`${name}Data`] = inline;
      dataRef = `#/components/schemas/${name}Data`;
    }
    entries.push({
      type,
      source,
      exchange: type.includes('.cmd.') ? 'bandada.commands' : 'bandada.events',
      dataSchema: dataRef.replace('#/components/schemas/', ''),
      message: name,
    });
  }
  const asOpenApi = { openapi: '3.1.0', info: { title: 'bandada-events', version: doc.info.version }, paths: {}, components: { schemas } };
  write(path.join(out, 'events/schemas.ts'), BANNER + (await toTypes(asOpenApi)));

  const dup = entries.map((e) => e.type).filter((t, i, a) => a.indexOf(t) !== i);
  if (dup.length > 0) throw new Error(`Duplicate event types: ${dup.join(', ')}`);
  entries.sort((a, b) => a.type.localeCompare(b.type));
  const map = entries.map((e) => `  '${e.type}': S['${e.dataSchema}'];`).join('\n');
  const meta = entries
    .map((e) => `  '${e.type}': { exchange: '${e.exchange}', source: ${e.source ? `'${e.source}'` : 'null'}, message: '${e.message}' },`)
    .join('\n');
  write(
    path.join(out, 'events/index.ts'),
    `${BANNER}import type { components } from './schemas';

type S = components['schemas'];

/** CloudEvent \`type\` (= routing key) mapped to the type of its \`data\`. */
export interface EventDataMap {
${map}
}

export type EventType = keyof EventDataMap;
export type EventData<T extends EventType> = EventDataMap[T];

export const eventTypes = [
${entries.map((e) => `  '${e.type}',`).join('\n')}
] as const satisfies readonly EventType[];

export const eventMeta = {
${meta}
} as const satisfies Record<EventType, { exchange: 'bandada.events' | 'bandada.commands'; source: string | null; message: string }>;

export type { components as EventSchemas } from './schemas';
`,
  );
  return entries.length;
}

async function genGraphql() {
  const schema = path.join(contracts, 'graphql/admin.graphql');
  await generate(
    {
      schema,
      generates: {
        [path.join(out, 'graphql/admin.ts')]: {
          plugins: ['typescript'],
          config: {
            enumsAsTypes: true,
            avoidOptionals: { field: true, inputValue: false, object: false },
            scalars: { DateTime: 'string', Date: 'string', UUID: 'string', JSON: 'unknown', Long: 'number' },
            skipTypename: true,
          },
        },
      },
    },
    true,
  );
  const file = path.join(out, 'graphql/admin.ts');
  fs.writeFileSync(file, `/* eslint-disable */\n${fs.readFileSync(file, 'utf8')}`);
}

const services = await genOpenApi();
const events = await genEvents();
await genGraphql();
console.log(`contracts-ts: ${services.length} openapi modules (${services.join(', ')}), ${events} event types, graphql admin`);
